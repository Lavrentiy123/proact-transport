def render(card: dict) -> str:
    items = qa(card)
    lines = ["# Шпаргалка: ответы жюри по ML и данным", "",
             f"> Сгенерировано `src/product/render_qa.py` из `models/model_card.json` (model_version "
             f"`{card.get('model_version', '?')}`). Ответ — не больше 3 предложений.", ""]
    for i, (q, a) in enumerate(items, start=1):
        lines += [f"## {i}. {q}", "", a, ""]
    return "\n".join(lines)


def main() -> int:
    card = json.loads((ROOT / "models" / "model_card.json").read_text(encoding="utf-8"))
    out = ROOT / "docs" / "pitch" / "qa_ml.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(card), encoding="utf-8")
    print(f"written {out.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
