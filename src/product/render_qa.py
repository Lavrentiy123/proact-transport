def extra_qa(card: dict) -> list[tuple[str, str]]:
    """Запасные вопросы: то, что жюри вероятно спросит после аудита (честные формулировки и границы решения)."""
    det = card.get("detector", {})
    mlp = card.get("m_online_mlp", {})
    oe60 = card.get("online_eval", {}).get("tick_60s", {})
    oos = card.get("online_eval", {}).get("out_of_sample_lobo", {})
    items = []
    if oe60.get("share_issued_before_actual_arrival") is not None:
        warned = (f" Для незнакомого борта из {oos['late_events']} реальных опозданий > 2 мин модель заранее предсказала "
                  f"{100 * oos['late_warned_share']:.0f} %, а её предупреждения верны в {100 * oos['warning_precision']:.0f} % случаев."
                  if oos.get("late_warned_share") is not None else "")
        items.append(("Докажите, что прогноз не «задним числом».",
                      f"{100 * oe60['share_issued_before_actual_arrival']:.0f} % прогнозов выданы до фактического прибытия: минимальный "
                      f"запас — {oe60['actual_lead_min_s']:.0f} с, медианный — {oe60['actual_lead_p50_s'] / 60:.1f} мин (сверка с фактами "
                      "test, только для оценки)." + warned))
    lb = lb_value()
    if lb is not None and lb >= 0.995:
        ds = card["m_ds"]
        items.append(("Скор 1.00 — не «математический» ли это трюк?",
                      f"Нет: сабмит — прогноз CatBoost ({ds['iterations']} деревьев × 5 сидов, 34 признака телеметрии и "
                      f"расписания) без фактов validate. Шкала платформы упирается в 1 уже при нашей ошибке: на тесте "
                      f"организаторов {fmt(ds['official_mae'])} с против {fmt(card['baselines']['official_cur_dev'])} с у "
                      f"бейзлайна. Для незнакомого автобуса честная цифра — LOBO {fmt(ds['lobo_mae'])} с, её и называем."))
    items += [
        ("Откуда шкала «0.70 = MAE 74 с»?",
         "Это наша оценка: один раз посчитали MAE двух тривиальных прогнозов на validate («0» и «cur_dev») и вывели линейную "
         "шкалу. Модели по фактам validate не оценивали и не выбирали; настоящий скор — только тот, что показала платформа"
         + (f" ({lb:.2f}: шкала насыщается раньше нашей оценки)." if lb is not None else ".")),
        ("Что будет, если ML-ядро упадёт?",
         "Backend открывает circuit breaker и до возврата ml-core прогнозирует «по расписанию» (задержка 0) с "
         "quality=fallback — это точнее прежнего правила: MAE 103 против 136 с. На дашборде жёлтый баннер и отметка в "
         "карточке; сервис не падает, ml-core подхватывается автоматически."),
        ("Есть ли What-If?",
         "Да, в карточке алерта: ползунок средней скорости до целевой остановки пересчитывает отклонение и время прибытия. "
         "Дистанцию берём из рекомендации backend, а при скорости, которую подразумевает прогноз модели, оценка совпадает с "
         "прогнозом; стоянки на промежуточных остановках не учитываются, это честно подписано. Отдельно — калькулятор "
         "ожидания пассажиров (EWT): межрейсовая стоянка ≤ 60 с сокращает ожидание на 0.79 мин на пассажира."),
        ("Делаете ли вы map matching?",
         "Мы привязываем GPS к плановым остановкам детектором прибытий с монотонным указателем и окном по текущему "
         f"отклонению: {100 * det.get('coverage', 0.842):.0f} % остановок, {100 * det.get('within30', 0.774):.0f} % — точнее ±30 с. "
         "Полноценный map matching на граф дорог — в планах: для прогноза задержки хватает привязки к остановкам."),
        ("Видите ли вы «падение скорости у перекрёстка» и «долгую посадку»?",
         "Данных о перекрёстках нет, поэтому перекрёстки отдельно не выделяем. Зато по телеметрии различаем стоянку вне "
         "остановок — причина «затор» — и стоянку в 30 м от остановки — «долгая посадка»; причина считается окклюзией "
         "признаков и показывается с числовым доказательством."),
        ("Как защищён API?",
         "Для демо — внутри доверенного контура: эксперт на QA-сессии сказал, что авторизация операторов не нужна (25:39). "
         "Для продакшена — шлюз с авторизацией и CORS; сервисы уже разделены, это конфигурация, а не переписывание."),
    ]
    if mlp:
        items.append(("Почему у CatBoost на потоке вес 0, а у простой модели по расписанию — 0.5?",
                      f"Так решила честная проверка на незнакомом борту: полный CatBoost на телеметрии — {fmt(mlp.get('lobo_mae_cat'))} с, "
                      f"PyTorch MLP — {fmt(mlp.get('lobo_mae_mlp'))} с, а ансамбль CatBoost по расписанию + MLP — "
                      f"{fmt(mlp.get('lobo_mae_blend'))} с. Телеметрические деревья переобучаются на знакомых бортах."))
    return items


def render(card: dict) -> str:
    items = qa(card)
    lines = ["# Шпаргалка: ответы жюри по ML и данным", "",
             f"> Сгенерировано `src/product/render_qa.py` из `models/model_card.json` (model_version "
             f"`{card.get('model_version', '?')}`). Ответ — не больше 3 предложений.", ""]
    for i, (q, a) in enumerate(items, start=1):
        lines += [f"## {i}. {q}", "", a, ""]
    extra = extra_qa(card)
    if extra:
        lines += ["## Запасные вопросы", ""]
        for q, a in extra:
            lines += [f"### {q}", "", a, ""]
    return "\n".join(lines)


def main() -> int:
    card = json.loads((ROOT / "models" / "model_card.json").read_text(encoding="utf-8"))
    out = ROOT / "docs" / "pitch" / "qa_ml.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(card), encoding="utf-8")
    print(f"written {out.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
